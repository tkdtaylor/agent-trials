from src.agent_wrapper import AgentResponse, ArmorGuard
from src.agents.tool_use_agent import ToolUseAgent


def stub_decide(specs: list[dict]):
    def _decide(query: str) -> list[dict]:
        return specs

    return _decide


def stub_execute(result: str):
    def _execute(tool: str, args: dict) -> str:
        return result

    return _execute


def stub_generate(answer: str):
    def _generate(query: str, tool_calls: list[dict]) -> str:
        return answer

    return _generate


