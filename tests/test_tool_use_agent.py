# --- callable wiring ---


def test_decide_tools_called_with_user_query():
    # TC-013-14
    received: list[str] = []

    def _decide(query: str) -> list[dict]:
        received.append(query)
        return []

    ToolUseAgent(_decide, stub_execute(""), stub_generate("")).process_request("my query")
    assert received == ["my query"]


def test_execute_tool_called_with_tool_name_and_args():
    # TC-013-15
    received: list = []

    def _execute(tool: str, args: dict) -> str:
        received.append((tool, args))
        return "r"

    ToolUseAgent(
        stub_decide([{"tool": "search", "args": {"q": "x"}}]),
        _execute,
        stub_generate(""),
    ).process_request("q")
    assert received == [("search", {"q": "x"})]


def test_generate_called_with_query_and_completed_tool_calls():
    # TC-013-16
    received: list = []

    def _generate(query: str, tool_calls: list[dict]) -> str:
        received.append((query, tool_calls))
        return "ok"

    ToolUseAgent(
        stub_decide([{"tool": "search", "args": {"q": "x"}}]),
        stub_execute("r"),
        _generate,
    ).process_request("my query")
    assert received == [("my query", [{"tool": "search", "args": {"q": "x"}, "result": "r"}])]


