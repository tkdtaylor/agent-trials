from src.agent_wrapper import AgentResponse, ArmorGuard
from src.agents.multi_turn_agent import MultiTurnAgent


def stub_generate(answer: str):
    def _generate(query: str, history: list[dict]) -> str:
        return answer

    return _generate


# --- Protocol attributes ---


