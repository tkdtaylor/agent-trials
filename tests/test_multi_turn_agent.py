# --- History management ---


def test_history_empty_at_construction():
    # TC-014-09
    assert MultiTurnAgent(stub_generate(""))._history == []


def test_history_has_user_and_assistant_after_one_call():
    # TC-014-10
    agent = MultiTurnAgent(stub_generate("hi"))
    agent.process_request("hello")
    assert agent._history == [
        {"role": "user", "content": "hello"},
        {"role": "assistant", "content": "hi"},
    ]


def test_history_grows_to_four_after_two_calls():
    # TC-014-11
    agent = MultiTurnAgent(stub_generate("r"))
    agent.process_request("a")
    agent.process_request("b")
    assert len(agent._history) == 4


def test_history_roles_are_user_or_assistant_only():
    # TC-014-12
    agent = MultiTurnAgent(stub_generate("r"))
    agent.process_request("a")
    agent.process_request("b")
    assert all(e["role"] in {"user", "assistant"} for e in agent._history)


