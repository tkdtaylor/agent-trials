# --- generate wiring ---


def test_generate_called_with_user_input():
    # TC-014-15
    received_queries: list[str] = []

    def _generate(query: str, history: list[dict]) -> str:
        received_queries.append(query)
        return "r"

    MultiTurnAgent(_generate).process_request("my input")
    assert received_queries == ["my input"]


def test_generate_receives_history_including_current_user_message_on_second_call():
    # TC-014-16
    received_histories: list = []

    def _generate(query: str, history: list[dict]) -> str:
        received_histories.append(list(history))
        return "reply"

    agent = MultiTurnAgent(_generate)
    agent.process_request("first")
    agent.process_request("second")

    second_history = received_histories[1]
    assert {"role": "user", "content": "first"} in second_history
    assert {"role": "assistant", "content": "reply"} in second_history
    assert {"role": "user", "content": "second"} in second_history


def test_history_does_not_bleed_between_instances():
    # TC-014-17
    a = MultiTurnAgent(stub_generate("ra"))
    b = MultiTurnAgent(stub_generate("rb"))
    a.process_request("hello")
    b.process_request("world")
    assert len(a._history) == 2
    assert len(b._history) == 2
    assert a._history[0]["content"] == "hello"
    assert b._history[0]["content"] == "world"


# --- ArmorGuard integration ---


def test_multi_turn_agent_works_inside_armor_guard():
    # TC-014-18
    result = ArmorGuard(MultiTurnAgent(stub_generate("reply")), armor_client=None).process("ping")
    assert result == "reply"
